package input

// 中文标点。只有一个元素的直接替换；有多个元素的按次序交替（左右引号）。
// 表里没有的字符照常交给应用，避免影响写代码时打的 - / = + * | 之类。
var punctTable = map[byte][]string{
	',':  {"，"},
	'.':  {"。"},
	'?':  {"？"},
	'!':  {"！"},
	':':  {"："},
	';':  {"；"},
	'(':  {"（"},
	')':  {"）"},
	'<':  {"《"},
	'>':  {"》"},
	'[':  {"【"},
	']':  {"】"},
	'{':  {"「"},
	'}':  {"」"},
	'/':  {"、"},
	'\\': {"、"},
	'~':  {"～"},
	'^':  {"……"},
	'_':  {"——"},
	'$':  {"￥"},
	'"':  {"“", "”"},
	'\'': {"‘", "’"},
}

// numberPunct 返回数字后面应保持半角的标点。只处理句号：
// 3.14 不该变成 3。14。
func numberPunct(prevDigit bool, ch byte) (string, bool) {
	if prevDigit && ch == '.' {
		return ".", true
	}
	return "", false
}
